fn lis(values: &[i64]) -> String {
    let mut tails: Vec<i64> = Vec::new();
    for &x in values {
        let i = tails.partition_point(|&t| t < x);
        if i == tails.len() {
            tails.push(x);
        } else {
            tails[i] = x;
        }
    }
    format!("{}:{}", tails.len(), h31(tails.iter().copied()))
}
