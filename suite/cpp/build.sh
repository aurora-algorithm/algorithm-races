#!/bin/bash
# Builds the C++ kernels with one compiler, each with its documented release flags and nothing else (no LTO, no
# -march=native, no -ffast-math). The third-party C/C++ libraries (deps.sh) are compiled by the same compiler with
# the same optimisation level, once per compiler (obj/<target>/tp, kept between builds).
#
# usage (from kernels/cpp):  ./build.sh msvc|msvc-novec|clang|gcc [--werror]  |  ./build.sh warnings
#   msvc   cl /O2 /std:c++latest (Windows; MSVC environment from $CPP_VCVARS, captured once)  -> bin/kernels-msvc.exe
#   msvc-novec  the same with /D_USE_STD_VECTOR_ALGORITHMS=0 (the STL's out-of-line vectorised algorithms off,
#          every file and library rebuilt with it)                                 -> bin/kernels-msvc-novec.exe
#   clang  ${CPP_CLANG:-clang++} -O3 -std=c++23 (on Windows: against the MSVC headers and libraries)
#                                                                            -> bin/kernels-clang[.exe]
#   gcc    ${CPP_GCC:-g++} -O3 -std=c++23 (on Windows: WinLibs MinGW-w64 UCRT, linked -static)
#                                                                            -> bin/kernels-gcc[.exe]
#   --werror   warnings (-Wall -Wextra, /W4) are errors
#   warnings   builds every compiler this machine has with --werror (the lint step)
#
# Our sources always compile with -Wall -Wextra (/W4); third-party code is compiled and included with warnings off.
set -euo pipefail
cd "$(dirname "$0")"

WIN=0
EXE=""
if [ "${OS:-}" = "Windows_NT" ]; then WIN=1; EXE=".exe"; fi
PY="${PY312:-${PYTHON:-python3}}"
JOBS="${CPP_JOBS:-$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 4)}"
TP=third_party
BOTAN_SRC="$TP/Botan-3.14.1"
BOTAN_MODULES=sha2_32,sha2_32_x86,sha2_32_armv8,sha2_32_simd,sha2_32_avx2,bcrypt,argon2,argon2fmt,argon2_simd64,argon2_simd4x64,argon2_avx512,system_rng,hex,cpuid
SRCS=(src/*.cpp)
# zlib without its gz* file API (not used; it needs the unistd.h that zlib's configure detects)
ZLIB_SRCS=("$TP"/zlib-1.4/{adler32,compress,crc32,deflate,infback,inffast,inflate,inftrees,trees,uncompr,zutil}.c)
ZSTD_SRCS=("$TP"/zstd-1.5.7/lib/common/*.c "$TP"/zstd-1.5.7/lib/compress/*.c "$TP"/zstd-1.5.7/lib/decompress/*.c)

die() { echo "error: $*" >&2; exit 1; }

# Runs "$@" for every remaining argument as a background job, at most $JOBS at a time; fails if any job failed.
parallel() {
  local fn="$1" pids=() f rc=0
  shift
  for f in "$@"; do
    "$fn" "$f" &
    pids+=($!)
    if [ ${#pids[@]} -ge "$JOBS" ]; then
      wait "${pids[0]}" || rc=1
      pids=("${pids[@]:1}")
    fi
  done
  for f in ${pids[@]+"${pids[@]}"}; do wait "$f" || rc=1; done
  return $rc
}

obj_name() { local base="${1##*/}"; echo "${base%.*}.o"; }

# The MSVC environment (INCLUDE, LIB, LIBPATH, PATH) that vcvars64.bat sets, captured once into obj/msvc-env.sh.
msvc_env() {
  local env_sh=obj/msvc-env.sh bat=obj/vcvars-env.bat
  [ -n "${CPP_VCVARS:-}" ] || die "CPP_VCVARS (the path of vcvars64.bat) is not set"
  mkdir -p obj
  if [ ! -s "$env_sh" ]; then
    printf '@call "%s" >nul\r\n@set\r\n' "$(cygpath -w "$CPP_VCVARS")" >"$bat"
    cmd.exe //c "$(cygpath -w "$bat")" | tr -d '\r' | "$PY" -c '
import shlex, subprocess, sys
for line in sys.stdin:
    name, _, value = line.rstrip("\n").partition("=")
    if name.upper() in ("INCLUDE", "LIB", "LIBPATH", "EXTERNAL_INCLUDE"):
        print(f"export {name.upper()}={shlex.quote(value)}")
    elif name.upper() == "PATH":
        unix = subprocess.run(["cygpath", "-u", "-p", value], capture_output=True, text=True).stdout.strip()
        print(f"export PATH={shlex.quote(unix)}")
' >"$env_sh.tmp"
    mv "$env_sh.tmp" "$env_sh"
  fi
  # shellcheck disable=SC1090
  source "$env_sh"
  command -v cl.exe >/dev/null || die "cl.exe not found after vcvars64.bat"
}

botan_amalgamation() {
  local out="$OBJ/botan" cc="$1" os="$2" cpu="$3"
  [ -s "$out/botan_all.cpp" ] && return
  mkdir -p "$out"
  (cd "$out" && "$PY" "$OLDPWD/$BOTAN_SRC/configure.py" --cc="$cc" --os="$os" --cpu="$cpu" --cc-min-version=0.0 \
    --amalgamation --minimized-build --enable-modules="$BOTAN_MODULES" --disable-shared-library \
    --without-documentation --without-compilation-database --with-build-dir=build >configure.log 2>&1) ||
    die "Botan configure failed: $out/configure.log"
}

write_build_info() {
  local flags="$1" file="$OBJ/build_info.hpp"
  local text="// generated by build.sh
#pragma once
namespace kernels {
inline constexpr const char* kBuildFlags = \"$flags\";
}"
  [ -f "$file" ] && [ "$(cat "$file")" = "$text" ] && return
  echo "$text" >"$file"
}

# GNU-style drivers: clang++ and g++ (and their C compilers for zlib and zstd).
gnu_build() {
  local cxx="$1" cc="$2" botan_cc="$3"
  local os cpu
  if [ "$WIN" = 1 ]; then
    os=windows cpu=x86_64
    [ "$TARGET" = gcc ] && os=mingw
    # clang++ (MSVC target) would pick a Visual Studio by itself; the vcvars environment pins the same MSVC 14.38
    # headers and libraries that cpp-msvc uses.
    if [ "$TARGET" = clang ] && [ -n "${CPP_VCVARS:-}" ]; then msvc_env; fi
  else
    os=$(uname -s | tr '[:upper:]' '[:lower:]'); [ "$os" = darwin ] && os=macos
    cpu=$(uname -m); [ "$cpu" = aarch64 ] && cpu=arm64
  fi
  botan_amalgamation "$botan_cc" "$os" "$cpu"
  OPT=(-O3 -DNDEBUG)
  # On arm64 clang and gcc fuse x*y + z into one FMA by default, which changes the last digits of nbody and
  # spectral-norm; the i7 (x86-64 baseline, no FMA instructions) cannot fuse, so the flag only matters off the i7.
  if [ "$WIN" = 0 ] && [ "$cpu" = arm64 ]; then OPT+=(-ffp-contract=off); fi
  CXXSTD=(-std=c++23)
  INCS=(-I"$OBJ" -isystem "$TP/include" -isystem "$TP/multiprecision-Boost_1_92_0/include"
    -isystem "$TP/boost-1.92.0/include" -isystem "$TP/zlib-1.4" -isystem "$TP/zstd-1.5.7/lib" -isystem "$OBJ/botan")
  WARN=(-Wall -Wextra)
  [ "$WERROR" = 1 ] && WARN+=(-Werror)
  LINK=()
  if [ "$WIN" = 1 ]; then
    LINK+=(-lbcrypt)
    # MinGW libstdc++ keeps std::print's console code (vprint_unicode) in libstdc++exp; only main.cpp's output uses it.
    [ "$TARGET" = gcc ] && LINK+=(-static -lstdc++exp)
  fi
  write_build_info "$(basename "$cxx") ${OPT[*]} ${CXXSTD[*]}${LINK[*]+ ${LINK[*]}}"
  CXX_BIN="$cxx" CC_BIN="$cc"
  cc_tp() { [ -s "$OBJ/tp/$(obj_name "$1")" ] || "$CC_BIN" "${OPT[@]}" -w -DZSTD_DISABLE_ASM -I"$TP/zlib-1.4" -c "$1" -o "$OBJ/tp/$(obj_name "$1")"; }
  cxx_botan() {
    [ -s "$OBJ/tp/botan_all.o" ] || "$CXX_BIN" "${OPT[@]}" "${CXXSTD[@]}" -w -isystem "$OBJ/botan" -c "$OBJ/botan/botan_all.cpp" -o "$OBJ/tp/botan_all.o"
  }
  cxx_src() { "$CXX_BIN" "${OPT[@]}" "${CXXSTD[@]}" "${WARN[@]}" "${INCS[@]}" -c "$1" -o "$OBJ/src/$(obj_name "$1")"; }
  mkdir -p "$OBJ/tp" "$OBJ/src"
  cxx_botan &
  local botan_pid=$!
  parallel cc_tp "${ZLIB_SRCS[@]}" "${ZSTD_SRCS[@]}"
  parallel cxx_src "${SRCS[@]}"
  wait "$botan_pid"
  "$CXX_BIN" "${OPT[@]}" "$OBJ"/src/*.o "$OBJ"/tp/*.o ${LINK[@]+"${LINK[@]}"} -o "bin/kernels-$TARGET$EXE"
}

msvc_build() {
  [ "$WIN" = 1 ] || die "cpp-msvc builds on Windows only"
  msvc_env
  botan_amalgamation msvc windows x86_64
  export MSYS_NO_PATHCONV=1
  OPT=(-O2 -EHsc -MD -DNDEBUG)
  local flags="cl /O2 /EHsc /MD /DNDEBUG /std:c++latest"
  if [ "$TARGET" = msvc-novec ]; then
    OPT+=(-D_USE_STD_VECTOR_ALGORITHMS=0)
    flags+=" /D_USE_STD_VECTOR_ALGORITHMS=0"
  fi
  CXXSTD=(-std:c++latest)
  INCS=(-I"$OBJ" -external:W0 -external:I"$TP/include" -external:I"$TP/multiprecision-Boost_1_92_0/include"
    -external:I"$TP/boost-1.92.0/include" -external:I"$TP/zlib-1.4" -external:I"$TP/zstd-1.5.7/lib" -external:I"$OBJ/botan")
  WARN=(-W4)
  [ "$WERROR" = 1 ] && WARN+=(-WX)
  write_build_info "$flags"
  cc_tp() { [ -s "$OBJ/tp/$(obj_name "$1")" ] || cl.exe -nologo "${OPT[@]}" -W0 -DZSTD_DISABLE_ASM -c "$1" -Fo"$OBJ/tp/$(obj_name "$1")" >/dev/null; }
  cxx_botan() {
    [ -s "$OBJ/tp/botan_all.o" ] || cl.exe -nologo "${OPT[@]}" "${CXXSTD[@]}" -bigobj -W0 -I"$OBJ/botan" -c "$OBJ/botan/botan_all.cpp" -Fo"$OBJ/tp/botan_all.o" >/dev/null
  }
  cxx_src() { cl.exe -nologo "${OPT[@]}" "${CXXSTD[@]}" "${WARN[@]}" "${INCS[@]}" -c "$1" -Fo"$OBJ/src/$(obj_name "$1")" | grep -v "^$(basename "$1")\$" || true; test -s "$OBJ/src/$(obj_name "$1")"; }
  mkdir -p "$OBJ/tp" "$OBJ/src"
  rm -f "$OBJ"/src/*.o
  cxx_botan &
  local botan_pid=$!
  parallel cc_tp "${ZLIB_SRCS[@]}" "${ZSTD_SRCS[@]}"
  parallel cxx_src "${SRCS[@]}"
  wait "$botan_pid"
  local link_out
  # cl prints link errors on stdout next to one D9024 line per object; keep only the errors.
  link_out=$(cl.exe -nologo "$OBJ"/src/*.o "$OBJ"/tp/*.o bcrypt.lib -Fe"bin/kernels-$TARGET.exe" 2>&1) ||
    { grep -v D9024 <<<"$link_out" >&2; die "link failed: bin/kernels-$TARGET.exe"; }
}

build() {
  TARGET="$1"
  OBJ="obj/$TARGET"
  mkdir -p bin "$OBJ"
  ./deps.sh
  rm -f "$OBJ"/src/*.o
  case "$TARGET" in
    msvc | msvc-novec) msvc_build ;;
    clang)
      local cxx="${CPP_CLANG:-clang++}"
      gnu_build "$cxx" "${cxx%++*}${cxx##*++}" "$([ "$WIN" = 1 ] && echo clangcl || echo clang)" ;;
    gcc)
      local cxx="${CPP_GCC:-g++}"
      gnu_build "$cxx" "${cxx%g++*}gcc${cxx##*g++}" gcc ;;
    *) die "unknown target $TARGET (msvc|msvc-novec|clang|gcc)" ;;
  esac
  echo "built bin/kernels-$TARGET$EXE"
}

WERROR=0
case "${1:-}" in
  msvc | msvc-novec | clang | gcc)
    [ "${2:-}" = --werror ] && WERROR=1
    build "$1" ;;
  warnings)
    # Every compiler this machine has (the i7: CPP_VCVARS, CPP_CLANG, CPP_GCC; elsewhere CPP_CLANG / CPP_GCC or the
    # defaults), with warnings as errors.
    WERROR=1
    built=0
    if [ "$WIN" = 1 ] && [ -n "${CPP_VCVARS:-}" ]; then (build msvc); built=1; fi
    if [ -n "${CPP_CLANG:-}" ] || { [ "$WIN" = 0 ] && command -v clang++ >/dev/null; }; then (build clang); built=1; fi
    if [ -n "${CPP_GCC:-}" ]; then (build gcc); built=1; fi
    [ "$built" = 1 ] || die "no C++ compiler configured (CPP_VCVARS, CPP_CLANG, CPP_GCC)"
    echo "warnings: none" ;;
  *)
    echo "usage: $0 msvc|msvc-novec|clang|gcc [--werror] | warnings" >&2; exit 2 ;;
esac
